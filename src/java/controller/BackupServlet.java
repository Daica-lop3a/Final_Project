package controller;

import dao.AuditLogDAO;
import dao.DBContext;
import model.AppUser;

import java.io.IOException;
import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.ResultSet;
import java.sql.Statement;
import java.text.SimpleDateFormat;
import java.util.Date;
import javax.servlet.ServletException;
import javax.servlet.annotation.WebServlet;
import javax.servlet.http.HttpServlet;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;
import javax.servlet.http.HttpSession;

/**
 * Super Admin Backup and Disaster Recovery Servlet (Backup and Recovery - X)
 * Exports a full database snapshot for backup and disaster recovery.
 * Strictly accessible by Super Admin (SAD).
 */
@WebServlet("/system/backup")
public class BackupServlet extends HttpServlet {

    @Override
    protected void doGet(HttpServletRequest req, HttpServletResponse resp)
            throws ServletException, IOException {

        HttpSession session = req.getSession(false);
        AppUser user = (session != null) ? (AppUser) session.getAttribute("user") : null;

        if (user == null || !user.isSuperAdmin()) {
            resp.sendRedirect(req.getContextPath() + "/dashboard");
            return;
        }

        String timestamp = new SimpleDateFormat("yyyyMMdd_HHmmss").format(new Date());
        String filename = "SmartWasteDB_Backup_" + timestamp + ".sql";

        resp.setContentType("text/plain; charset=UTF-8");
        resp.setHeader("Content-Disposition", "attachment; filename=\"" + filename + "\"");

        OutputStreamWriter osw = new OutputStreamWriter(resp.getOutputStream(), StandardCharsets.UTF_8);
        PrintWriter writer = new PrintWriter(osw);

        writer.println("-- =====================================================================");
        writer.println("-- SMARTWASTE ENTERPRISE DISASTER RECOVERY BACKUP SNAPSHOT");
        writer.println("-- Generated By Super Admin: " + user.getFullName() + " (" + user.getUserId() + ")");
        writer.println("-- Timestamp: " + new SimpleDateFormat("yyyy-MM-dd HH:mm:ss").format(new Date()));
        writer.println("-- Target Database: SmartWasteDB");
        writer.println("-- =====================================================================\n");

        String[] tables = {
            "tblRoles", "tblAreas", "tblUsers", "tblUserAreas", "tblWasteBins",
            "tblSystemConfig", "tblBinReadings", "tblCollectionRequests",
            "tblMaintenance", "tblAlerts", "tblCitizenReports", "tblAdminPasswordRequests", "tblAuditLogs"
        };

        Connection conn = null;
        Statement stmt = null;

        try {
            conn = DBContext.getConnection();
            stmt = conn.createStatement();

            for (String table : tables) {
                writer.println("\n-- --------------------------------------------------");
                writer.println("-- TABLE DATA: " + table);
                writer.println("-- --------------------------------------------------");

                String query = "SELECT * FROM dbo." + table;
                ResultSet rs = null;
                try {
                    rs = stmt.executeQuery(query);
                    int colCount = rs.getMetaData().getColumnCount();

                    while (rs.next()) {
                        StringBuilder insert = new StringBuilder("INSERT INTO dbo." + table + " VALUES (");
                        for (int i = 1; i <= colCount; i++) {
                            Object val = rs.getObject(i);
                            if (val == null) {
                                insert.append("NULL");
                            } else if (val instanceof Number || val instanceof Boolean) {
                                insert.append(val);
                            } else {
                                String str = val.toString().replace("'", "''");
                                insert.append("N'").append(str).append("'");
                            }
                            if (i < colCount) insert.append(", ");
                        }
                        insert.append(");");
                        writer.println(insert.toString());
                    }
                } catch (Exception tableEx) {
                    writer.println("-- Notice: skipped table " + table + " (" + tableEx.getMessage() + ")");
                } finally {
                    if (rs != null) rs.close();
                }
            }

            AuditLogDAO.log(
                    user.getUserId(),
                    "DATABASE_BACKUP",
                    "DATABASE",
                    "SmartWasteDB",
                    null,
                    "Super Admin generated and downloaded disaster recovery database snapshot: " + filename,
                    req.getRemoteAddr()
            );

        } catch (Exception e) {
            writer.println("\n-- Backup generation encountered error: " + e.getMessage());
        } finally {
            DBContext.close(null, stmt, conn);
            writer.flush();
        }
    }
}
